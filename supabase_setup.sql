create table if not exists public.gym_checklist_records (
  id bigint generated by default as identity primary key,
  employee text not null,
  work_date date not null,
  shift text not null check (shift in ('오픈', '근무 중', '마감')),
  notes text not null default '',
  checks jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.gym_checklist_records enable row level security;

drop policy if exists "authenticated staff can read checklist records" on public.gym_checklist_records;
create policy "authenticated staff can read checklist records"
on public.gym_checklist_records for select to authenticated using (true);

drop policy if exists "authenticated staff can add checklist records" on public.gym_checklist_records;
create policy "authenticated staff can add checklist records"
on public.gym_checklist_records for insert to authenticated with check (true);

drop policy if exists "authenticated staff can update checklist records" on public.gym_checklist_records;
create policy "authenticated staff can update checklist records"
on public.gym_checklist_records for update to authenticated using (true) with check (true);

